export function getReference(metric: ReferenceMetric, profile: Pick<Profile, 'ageGroup' | 'sex'>) {
  if (!isAdultGroup(profile.ageGroup) || !profile.sex) return undefined;
  const [sample, mean, p25, p50, p75] = data[metric][profile.sex][profile.ageGroup];
  return { sample, mean, p25, p50, p75 };
}
