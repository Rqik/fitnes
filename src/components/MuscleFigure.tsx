export function MuscleFigure({ view, selected, statuses, onSelect }: {
  view: View;
  selected: Metric;
  statuses: Readonly<Partial<Record<Metric, RegionStatus>>>;
  onSelect: (metric: Metric) => void;
}) {
  const regions = view === 'front' ? front : back;
  const selectedRegion = regions.find(({ metric }) => metric === selected);

  return (
    <svg className="muscle-figure" viewBox="0 0 280 528" aria-hidden="true" focusable="false" strokeLinejoin="round">
      <AnatomyBase view={view} />
      {regions.map(({ metric, surface, shade, fibers, isCentered }) => (
        <g
          key={metric}
          className="muscle-region"
          data-metric={metric}
          data-status={statuses[metric] ?? 'none'}
          data-selected={selected === metric}
          fill="#c5cdd5"
          stroke="#73818d"
          strokeWidth="1.05"
          onClick={() => onSelect(metric)}
        >
          {(isCentered ? [undefined] : [undefined, mirror]).map((transform) => (
            <g key={transform ?? 'left'} transform={transform}>
              <path className="muscle-region-shape" d={surface} />
              {shade ? <path className="muscle-region-shade" d={shade} fill="#4e6375" fillOpacity=".13" stroke="none" pointerEvents="none" /> : null}
              {fibers ? <path className="muscle-region-detail" d={fibers} fill="none" stroke="#516373" strokeWidth=".72" strokeOpacity=".4" strokeLinecap="round" pointerEvents="none" /> : null}
            </g>
          ))}
        </g>
      ))}
      {selectedRegion ? (
        <g className="muscle-region-outline" fill="none" stroke="#263b4d" strokeWidth="1.9" pointerEvents="none">
          <path d={selectedRegion.surface} vectorEffect="non-scaling-stroke" />
          {selectedRegion.isCentered ? null : <path d={selectedRegion.surface} transform={mirror} vectorEffect="non-scaling-stroke" />}
        </g>
      ) : null}
    </svg>
  );
}
